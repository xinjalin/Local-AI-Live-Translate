function lcTranslate(lang, key, vars) {
  const dict = LC_I18N[lang] || LC_I18N['en'];
  let text = dict[key] || LC_I18N['en'][key] || '';
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, v);
  }
  return text;
}

// Language name for `code`, written in the `uiLang` language.
function lcLanguageName(code, uiLang) {
  const name = new Intl.DisplayNames([LC_INTL_CODE[uiLang] || uiLang], { type: 'language' })
    .of(LC_INTL_CODE[code] || code);
  return name.charAt(0).toLocaleUpperCase(uiLang) + name.slice(1);
}
